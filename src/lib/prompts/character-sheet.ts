/**
 * character-sheet.ts —— 角色标准像（角色卡的参考图）的提示词，带版本号
 *
 * ★ 这份提示词在 W1 是从 `scripts/make-demo-cards.mts` 里长出来的（两张演示卡就是它的产物），
 *   现在提到这里，理由是**它有两个消费者**了：那个脚本（预生成演示卡）与
 *   创作流第 3 步（家长现场做卡）。留在脚本里的话，第二条路会抄一份，然后开始漂。
 *
 * 三处约束是从 `gpt-image-2-style-library` 的 character-design-sheet 那一档抄来的
 * （它的 guidance 正是"定义身份锚点、服装、比例、版式，保持脸/发型/服装一致"），
 * 而它的两条 pitfall 被直接写成了约束：**单姿势单画面**（画面一挤就少画手指）、
 * **风格与构图分开成块**（混在一句话里，模型会把两者一起打折）。
 *
 * ★ 一张参考图只负责一件事：**"他是谁"**。所以背景是空的、表情是平的、构图是正的。
 *   场景、动作、光线全属于页级提示词（`image.ts`），把它们写进来会让这张图不再是"标准像"。
 *
 * ★ 2026-10-16 第 21 刀：**三个版本号一起进到 `@v2`**，改的是【构图】段里的一句
 *   ——背景从"极淡的暖米色平涂"改成"干净的纯白平涂"（用户："生成的人物也要是白底的"）。
 *   ★ 为什么为一句背景色升版本：`provenance.promptVersion` 的全部用处就是回答
 *     "这张图是哪份提示词出来的"，而背景是**看得见**的差别——不升版本，卡片墙上
 *     那两张白底与米底的图会共用同一个版本号，答辩时"这两张的提示词一样吗"就答反了。
 *   ★ **老卡不会因此变成 v2**：它们记的是生成那一刻的版本，照旧是 v1、照旧是米底，
 *     事实没被改写。"演示卡为什么是 v1"的答案就是"它们是居中的那一版画的"。
 *   ★ 三个版本号同进，是因为那一段【构图】**三份共用**（标准像 / 再画一版 / 用照片）。
 *     只升一份的后果是另外两份的图版本号骗人——而它们也变成白底了。
 */

import type { CharacterAnchor, StyleLock } from '../engine/domain.ts'

export const CHARACTER_SHEET_VERSION = 'character-sheet@v2'

/**
 * 「再画一版」用的提示词版本（工单 03）。
 *
 * ★ 为什么另起一个版本号而不是把它并进标准像那一份：
 *   provenance 记的是"这张图是哪份提示词出来的"。带建议的那一份比标准像那份**多一段**，
 *   两者出来的图不该共用一个版本号——共用之后，答辩时"这一版和上一版提示词一样吗"
 *   就答不上来。
 * ★ 不带建议时仍然走 `CHARACTER_SHEET_VERSION`：两份的字面差别只有【这一版要改的地方】
 *   那一段，其余逐字节相同。
 * ★ 版本号从 `@v1` 进到 `@v2` 是同一天的事（背景改白底），理由写在文件头那一段。
 */
export const CHARACTER_REVISE_VERSION = 'character-revise@v2'

/**
 * 「用他的照片出一张形象」用的提示词版本（工单 03 的第二条路）。
 *
 * ★ 为什么是第三个版本号，而不是复用 `CHARACTER_SHEET_VERSION`：
 *   这一份比标准像那份**多一段**（见 `fromPhoto`），而那一整段是决定这条路的成败的——
 *   参考图在 `revise` 那条路上是"上一版的插画"（照着画），在这条路上是"孩子本人的照片"
 *   （要**转成插画**，不能照抄构图）。亮出来的是同一张脸，但依据那份输入完全不同，
 *   所以 provenance 必须分得开：答辩时"这两张的提示词一样吗"要答得上。
 */
export const CHARACTER_PHOTO_VERSION = 'character-photo@v2'

/** 画风段。与 `docs/demo-book-art-prompts.md` 的既定描述一致（26 张成图都是这一套出来的） */
export const DEFAULT_STYLE_FRAGMENT =
  '温暖手绘绘本插画：水彩铺色打底 + 细彩铅轮廓线收形，可见纸质纹理，' +
  '高明度低饱和的粉彩色板，柔和的左上方统一光源，阴影无硬边'

/**
 * 建卡时写进 `card.style` 的那一份（画风 + 比例）。
 *
 * ★ 它上提到这里，是因为建卡的路有**两条**了（从零描述 / 用他的照片，工单 03 第二刀）。
 *   两份字面量各自写在自己的 route 里，漂的方式很安静：改了一边，另一边的孩子
 *   画出来是另一种画风，而两张卡都"合法"——没有一处会报错。
 * ★ 产品现在只有这一档画风（界面上它是个事实，不是下拉，见 `DEFAULT_STYLE_LABEL`）。
 */
export const DEFAULT_CARD_STYLE: StyleLock = {
  key: 'warm-handdrawn',
  promptFragment: DEFAULT_STYLE_FRAGMENT,
  ratio: '1:1',
}

/**
 * 界面上给人看的那三个字（工作台的画风那一格）。
 *
 * ★ 为什么贴在提示词旁边而不是写在组件里：它是上面那段话的**摘要**，
 *   两者说的必须是同一件事。分开写，改提示词的人不会想到去改界面，
 *   于是屏幕上写着"水彩"、画出来的是别的东西——这类漂移最难发现。
 *   盯住这条的是 `style.test.ts`。
 * ★ 产品现在**只有这一档**画风（`/api/cards` 建卡时写死 `warm-handdrawn`），
 *   所以界面上它是一个"事实"，不是一个下拉。做成下拉就是摆一个假控件。
 */
export const DEFAULT_STYLE_LABEL = '水彩'

export type CharacterSheetInput = {
  name: string
  /** 用来决定"小男孩/小女孩"这类词。给孩子自己用的称呼，不是账号 */
  childWord: string
  ageLabel: string
  anchors: readonly CharacterAnchor[]
  style?: StyleLock
  /**
   * 家长写下的「想改哪里」（工单 03 的「再画一版」）。
   *
   * ★ 它**只加一段指令，不动锚点**。锚点是"他长什么样"的判据，跨页不变；
   *   这一句只属于这一版（见 domain.ts 的 `Provenance.suggestion`）。
   * ★ 段落位置放在锚点之后、构图之前：模型对"先定义身份、再改一处、最后说构图"
   *   这个顺序更稳；把改动塞在锚点中间，实测容易让整张脸重新抽签。
   */
  revisionNote?: string
  /**
   * 参考图是**孩子本人的照片**（工单 03 的「用他的照片」那条路）。
   *
   * ★ 用一个布尔，而不是让调用方自己写这段话：这段话说的是**这张图该怎么用那张参考图**，
   *   是产品判断，不是用户输入。做成自由文本，第一个改它的人会把"保留面部特征"删掉，
   *   于是照片那条路安静地退化成"拿照片当风格参考"——画出来是另一个孩子，
   *   而没有任何一处会报错。
   * ★ 三件事必须一起说，缺一条就有一个具体的坏法：
   *   ① **保留他的脸和发型**——不说，模型会画一个"同年龄同性别"的平均小孩；
   *   ② **转成插画风格**——不说，会回来一张带照片质感的图，而参考图要逐页复用、
   *      还要和插画比对（ADR-0007 验的是插画比插画）；
   *   ③ **不要照抄照片的构图/姿势/背景**——不说，回来的是那张照片的描摹，
   *      头身比与站姿都不是标准像要的那个形状。
   */
  fromPhoto?: boolean
}

export function characterSheetPrompt(input: CharacterSheetInput): string {
  const style = input.style?.promptFragment || DEFAULT_STYLE_FRAGMENT
  const note = input.revisionNote?.trim() ?? ''
  return [
    `画一张儿童绘本的**角色标准像**：${input.name}，东亚面孔，${input.ageLabel}${input.childWord}。`,
    '',
    '【身份锚点——每一条都必须画出来，它们是后续所有页的核对依据】',
    ...input.anchors.map((anchor, index) => `${index + 1}. ${anchor.value}`),
    '',
    ...(input.fromPhoto
      ? [
          '【参考图是孩子本人的照片】保留他的面部特征、发型与肤色，把它画成这张绘本的插画形象。',
          '只借用"他是谁"，不要照抄照片的姿势、构图、背景与光线——那些由下面的构图段决定。',
          '',
        ]
      : []),
    ...(note === ''
      ? []
      : ['【这一版要改的地方——家长看过上一版之后提的，只改这里，别处保持与上一版一致】', note, '']),
    '【构图】竖构图居中，单人，站姿正面略偏 15 度，双手自然垂放，全身入画（头顶与脚底各留约 8% 空间）。',
    // ★ 白底（2026-10-16 第 21 刀，用户："生成的人物也要是白底的"，截图里三张角色卡：
    //   `public/demo/cards/` 那两张（小满/小宇）是白底，现场生成的那张是暖米色——
    //   而它们**本该是同一种**。上面那句原话是"一层极淡的暖米色平涂"，
    //   所以"不一致"这件事不是模型抽签，是这一行自己写着的。
    //   ★ 为什么是白而不是把演示卡改成米色：演示卡是**已经印出来的样板**，改它们等于重画；
    //   而白底在卡片墙与形象页上都是"衬纸"那一层的颜色，本来就该透出来。
    //   ★ 措辞取自 `docs/figure-art-prompts.md` §二 的【背景】段（"纯白 #FFFFFF…"那一句），
    //   但**比它多一句**：实测同一份提示词出一张，"无纹理"这一条挡不住模型给纸染上一层暖白
    //   （量到 #F7F7F3，角上通道极差 5、最小通道 243——见 `scripts/probe-portrait-background.mts`）。
    //   立绘那一批不介意这个（它们要抠底），而角色卡**看得出来**：卡面那一层是 #FFFFFF，
    //   差 3% 的白会显出一条淡淡的方块边。多出来的那一句专门打这件事。
    '背景必须是纯白 #FFFFFF（画纸本来的白）：不画纹理、地面、投影、接触阴影、光晕、外描边，',
    '也不要给背景染上米黄或灰色——它是纸，不是场景。',
    '不放任何场景物件——这张图只负责"他是谁"。',
    '视线看向画外，表情平和带一点好奇，不做夸张表情。',
    '',
    `【风格】${style}`,
    '',
    '【文字】画面内不出现任何文字、字母、数字、签名、水印。',
    '',
    '【约束】不要第二张脸；不要多余的手指（每只手 5 指为限）；不要成人的身材比例套在孩子身上；',
    '不要写实照片质感；不要深色、米色或彩色的背景；不要多格分镜、拼贴、画框、样机、阴影底板。',
  ].join('\n')
}

/**
 * 年龄档 → 提示词里的说法。
 *
 * ★ 用"几岁左右"而不是精确岁数：锚点里没有生日，编一个确切的数字会让模型
 *   画出一个我们没依据的年龄（而"4 岁"与"6 岁"画出来的脸差别很大）。
 */
export function ageLabelOf(ageBand: string): string {
  switch (ageBand) {
    case '4-':
      return '三四岁左右'
    case '4-6':
      return '四五岁左右'
    case '6-8':
      return '六到八岁'
    default:
      return '八岁以上'
  }
}
