    '假设选择点是第 6 页，那这一页就是这样——**九格平铺在这一页上**（不是一个嵌套的小对象、',
    '也**没有** `options` 数组）：',
    '{',
    '  "scene": "路口分成两条，一条钻进向日葵地，一条上过街天桥",',
