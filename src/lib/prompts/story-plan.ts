const RED_LINES = [
  '绝对不能出现：恐怖、暴力、死亡、自伤、歧视（性别/外貌/家庭结构）、危险动作的可模仿示范。',
  '可以出现情绪（害怕、难过、想妈妈），但必须在故事内被接住，不能悬着结束。',
  '不要写"教他做人"的段落。道理让孩子自己从情节里得出来；说教味是这一行最严的失败。',
].join('\n')

export type StoryPlanInput = {
  childName: string
  nameReading: string
  ageBand: AgeBand
  interestTags: readonly string[]
  lookTags: readonly string[]
  theme: string
  wish?: string
  form: BookForm
  /**
   * 页数。★ **两种形态的口径不同**（2026-10-18 共读版定的）：
   * - 独读版 = 这本书有多少页；
   * - 共读版 = **整条路读下来多少页**（不是全树节点数——走不到的那一支算钱不算长度）。
   *
   * ★ 这个区别必须留在这一句上，因为它是**成本**与**阅读长度**两个量的分家处：
   *   一本 8 页路长的共读版要画 ≈11 张图（两支各带一条尾巴，见 spec §零）。
   *   把 `pages` 说成"总页数"会让家长以为花的就是 8 张图的钱。
   */
  pages: number
  /**
   * 「让 AI 重写一版」时家长写的那句话（2026-10-17 的故事闸门）。
   *
   * ★ 它**只在这一条路上有值**：家长看完第一版故事之后说"结局改成她带着全班一起飞"，
   *   重编时把这句话贴进去。第一次编的时候它是 undefined。
   * ★ 措辞必须说清"重写整篇，不是打补丁"——不说的话，模型会保留原故事只改结尾，
   *   而家长要的是"按我说的这个方向重新长一遍"（他会拿新版与旧版对着看）。
   */
  reviseNote?: string
}

/** system：身份、硬约束、输出形状。不随书变化，所以可以整段缓存 */
export function storyPlanSystem(): string {
  return [
    '你是中文绘本的文字作者兼分镜师，写给 3–8 岁孩子听，由爸爸妈妈朗读。',
    '你的产出是一份 JSON 分镜表，不是散文——不要寒暄、不要解释你做了什么、不要围栏之外再加字。',
    '',
    '【输出形状】',
    '严格按下述结构输出：title 是书名（≤8 字，不要出现孩子名字，名字在页面上另排），',
    'nodes 是页表，顺序就是阅读顺序。',
    JSON.stringify(planJsonSchema()),
    '',
    /**
     * ★ 图标词表放在**系统提示词**里、并且写成 JSON 数组（2026-10-18，实测逼出来的）。
     *
     * 第一版把它写在用户提示词里的一句散文中间（"从这几个里挑最接近的一个：
     * dino / ship / rocket / … / drum"），**实测三次规划全败**，其中一次的原始输出是
     *
     *     "choice": { "dino / ship / rocket / … / drum": null }
     *
     * ——模型把整串词表当成了 JSON 的键。它形如数据的碎片，就该写成数据：
     * 数组字面量 + 说清"原样照抄一个"。这也与"schema 的事归系统提示词"这条分法一致：
     * 系统提示词管输出形状，用户提示词管这一本书的内容。
     */
    '【可选图标】（只有共读版的选择点用到）',
    `iconKey 只能从这一个数组里取一个，**原样照抄**（例如 "rocket"）：${JSON.stringify(CHOICE_ICONS)}`,
    '这些都不合适就挑最接近的那个，**不要自造新词、也不要把这一串抄进字段里**。',
    '',
    '【内容红线】',
    RED_LINES,
  ].join('\n')
}

export function storyPlanUser(input: StoryPlanInput): string {
  return [
    `主角：${input.childName}（名字念 ${input.nameReading}，别念错）。`,
    `年龄档：${input.ageBand}。语言规则：${AGE_RULES[input.ageBand]}`,
    input.interestTags.length > 0
      ? `爱好：${input.interestTags.join('、')}。至少让其中两项真的参与情节，不要只当背景板。`
      : '',
    input.lookTags.length > 0
      ? `外貌标签（形象由角色卡负责，这里只作参考，不要写进画面 prompt）：${input.lookTags.join('、')}。`
      : '',
    `主题：${input.theme}。`,
    input.wish
      ? `家长希望孩子从中得到：${input.wish}。注意这是**给作者的暗线**，不许写成台词。`
      : '',
    '',
    // ★ 重写那一段放在**最后**（紧跟表单字段说明之前）：它是这一轮的**追加指令**，
    //   接在最后才像是"在刚才那些要求之上，另外还有这一条"。
    //   ★ 措辞里三件事都是必需的：①这是家长看完第一版的意见；②**重写整篇**不是修补；
    //     ③上面那些年龄与形态的硬约束一条都不放松——不说第③条，模型会把注意力
    //     全放在新要求上，把"每句 12 字"这类规则丢掉。
    input.reviseNote
      ? [
          '【家长看过你的第一版之后的意见——请**按这个方向重写整篇**】',
          input.reviseNote,
          '注意：上面那些年龄档的语言规则、页数、红线条一条都不放松；' +
            '要重写的是故事本身（情节怎么发展、怎么收），不是只在原来的稿子上打补丁。',
        ].join('\n')
      : '',
    '',
    FORM_RULES[input.form].replaceAll('{pages}', String(input.pages)),
    '',
    '【每页的四个字段】',
    '- scene：这一页发生了什么（给插画与审核看，不印在页上）',
    '- body：朗读正文，一句一条，1–3 条',
    '- imagePrompt：**页级**画面描述（场景 / 动作 / 光线 / 构图）。' +
      '不要描述主角的长相——那是角色卡的职责，重复描述会打架；' +
      '不要要求画面里出现任何文字或数字；不要写"留白""安全边距"这类排版词。',
    '- mood：calm / wonder / joy / tense / tender / proud 之一，它决定配音语气',
  ]
    .filter(Boolean)
    .join('\n')
}
