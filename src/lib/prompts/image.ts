/**
 * image.ts —— 逐页画面的提示词组装（v1）。
 *
 * 这一文件是"学费进代码"的地方，下面每一条约束都对应仓库里一次实测踩坑：
 *
 * - 画面里一律不放任何文字（`docs/cover-art-prompts.md`：中文文字不可靠，错字、缺笔、乱码）。
 * - 不写"留白 / 安全边距"（`docs/demo-book-art-prompts.md` 云批次：会被读成留白，
 *   真画出白纸边）。
 * - 负极清单必须同时写"要出现什么"（同上 §五：只写"不要什么"会失效）。
 * - 角色段只从角色卡派生，页级 prompt 不许描述长相（一处真相，见 card.ts）。
 *
 * 组装顺序固定：画风 → 角色段 → 身份行 → 页级三项 → 负极清单 → 构图，中间夹着两个可选的
 * 修正块（`anchorNote` 模型上一轮的结论 → `fixNote` 人的更正），不写就是没有它们。
 * 顺序不是审美选择，是横评可比性的前提（ADR-0002 第二个理由）。
 */

import { ANCHOR_LABELS, type CharacterCard } from '../engine/domain.ts'
import { promptFragmentOf } from '../engine/character-card/card.ts'

/**
 * 提示词模板的版本。改模板就要改它，理由不是洁癖：`provenance.promptVersion` 记在每一张
 * 图上，而 W1 横评那些数字（同一份 prompt 的通过率、首次通过率）只有同一版本之间可比。
 *
 * 2026-10-16 `@v1` → `@v2`：多了一个可选尾块 `fixNote`（用户逐页重画时写的"这一次哪里
 * 不对"）。不写它的那些页逐字节与 v1 相同——但"这个模板能接受一句修正"是一件事，而版本号
 * 说的是模板，不是某一次调用的参数，所以它跟着升。
 *
 * 同一天 `@v2` → `@v3`：多了一行 `identityBlock`（"整本书就是这个孩子"，起因是"我提供给
 * 你的是男孩子，怎么生成出来有男孩有女孩子"那条报障）。这一版与前两版不再逐字节可比：
 * v1/v2 跑出来的那些数字是"没有身份不变式"那个模板的成绩。抬版本号正是为了让这件事在
 * `provenance` 里看得见。
 *
 * 2026-10-20 `@v3` → `@v4`：多了可选的 `anchorNote`——比对模型上一轮"哪几条锚点不像"的
 * 结论，回灌进下一次重画。这一版与前几版的关系与 v2→v3 那一次**不同**，别照着上面那句抄：
 * 第 1 次的提示词里没有 `anchorNote`（那时还没有任何结论），所以它逐字节仍然等于 v3，
 * 首次通过率照样可比；变的是重画那一次。所以"重画后通过率"这个数在 v3/v4 之间不是同一件
 * 事，而按 `provenance` 分档时两类图仍然混在一栏里（一页的第 1 次与第 2 次记的是同一个
 * `promptVersion`）。要分开算，看的是 `attempt`，不是版本号。
 *
 * 2026-10-20 再抬到 `@v5`：多了一句优先级（`PRECEDENCE_BLOCK`），并把 `本页画面` / `情节`
 * 两个值包进「」。这一版与前几版都不再逐字节可比（每一页都多了那一句），所以
 * "首次通过率""重画率"这些跨版本读数到此为止要按 `@v4` 封箱。v2 与 v4 那两次"可选块，
 * 所以首次逐字节相同"的判断不适用于这一次。
 */
export const IMAGE_PROMPT_VERSION = 'image-page@v5'

/** 负极清单。每条后面都跟一句"要出现什么"——只写不要，模型会画出一个它认为不要的反面 */
const NEGATIVE_BLOCK = [
  '避免出现：任何文字、字母、数字、签名、水印、画框边、分镜格；',
  '避免出现：多余的手指（每只手 5 指为限）、第二张脸、畸形的肢体、成人的身材比例套在孩子身上；',
  '避免出现：写实照片质感、恐怖的光影、尖锐的暗色阴影、血与伤口。',
  '应当出现的是：柔和的侧向暖光、清楚的轮廓、孩子约占画面高度的一半、留出走动的空间给文字排版。',
].join('\n')

/** 跨页构图约束：正文叠在左页下角，所以那块地方不能有重要内容（首页第二屏实测过） */
const COMPOSITION_BLOCK =
  '构图：主体偏右或居中，左下方约四分之一留出相对干净、可叠字的区域（不要画成白纸，只是不要放关键内容）。'

/**
 * 谁说了算那一句（2026-10-20 加）。
 *
 * 这一份提示词里有三类会打架的东西，而在它之前没有一处说明冲突时谁赢：
 *
 * - 角色段 + 身份行：来自角色卡（`promptFragmentOf` / `identityBlock`），不可改，
 *   它回答"这个孩子是谁"。
 * - 本页画面 / 情节：来自 `story.json`，家长可以逐字改（那个 PUT 只过信封校验）。
 * - `fixNote`：家长在重画对话框里手输，可以改。
 * - 构图 / 负极清单：代码里的两段常量，不可改，它是这套提示词唯一的红线。
 *
 * 不说清谁赢，一句"这一次改成两只手各拿一把刀"就会与负极清单正面撞上，而模型照哪一条全看
 * 运气——出图这条路没有文字闸，事后只有那一档不可复现的画面审核兜着。所以这一句不是在给
 * 模型加限制，是把它本来就在做的那件事写下来：负极清单（"避免出现：血与伤口…"）不该被
 * 任何一页的具体描述盖过。
 * ★ 少写这一句的症状不是报错，是"偶尔画出一张不该出现的图"，而它没有可复现的判据。
 */
const PRECEDENCE_BLOCK =
  '优先级：角色描述、构图、「避免出现」这三段，**压过**书名、这一页的情节描述、' +
  '以及任何"改成…"的要求。两者冲突时，**按前三段来画**。'

export type PagePromptInput = {
  card: CharacterCard
  /** 页级描述，来自规划的 imagePrompt 字段 */
  page: string
  scene: string
  mood: string
  /**
   * 家长对这一页这一次重画的补充（"这一次哪里不对"）。逐页重画时才有。
   *
   * 它是人的更正，不是模型的产物，所以位置与措辞都要让它显眼：放在页级那三项之后、构图与
   * 负极清单之前——接在最后的话它会与那一长串"避免出现…"抢注意力，而它说的是"上一张哪里
   * 错了"，比那三行通用约束更要紧。不写就是没有这一块（`filter(Boolean)`），所以没写过
   * 补充的页逐字节与 v1 相同。
   */
  fixNote?: string
  /**
   * 上一轮重画被否掉的那几条锚点，由 `anchorNoteOf` 从比对模型的结论拼出来。
   * 只有"这一页上一次没过、于是要再画一次"时才有（`illustrate.ts`）。
   *
   * 它与 `fixNote` 同形但不是一回事，两个差别都要留住：`fixNote` 是人写的更正（家长点重画时
   * 才有），这一句是比对模型上一版的结论（"清单里这几条不像"）；所以人和模型同时说话时，
   * 人要排在后面——人那句话是命令，模型这一句是诊断。拼装顺序见 `pagePrompt` 里那两个 ★ 块。
   */
  anchorNote?: string
  /**
   * 这一页的主角称呼（小男孩 / 小女孩 / 孩子），由 `childWordOf` 从孩子那两样
   * （选的性别、外貌标签）算出来。
   *
   * 2026-10-16 补上它，起因是一条用户报障：「我提供给你的是男孩子，
   *   怎么生成出来有男孩有女孩子」（8 页里 1/4/6 像男孩，2/3/5/7/8 像女孩）。
   *   查下来这一格是整条链上唯一没接上的一环：
   *   · 这个称呼原本只进了标准像的 prompt（`character-sheet.ts` 的 `childWord`）；
   *   · 逐页那条路拼的是 `promptFragmentOf(card)`，而锚点里一个性别词都没有
   *     （实测那张卡：脸圆润 / 眼圆黑 / 黑直短发 / 头身比 1:4 / 蓝灰鸭舌帽…）；
   *   · 更要紧的是有几页的画面描述里根本没有这个孩子：第 2 页写的是
   *     "纸箱内部的主观视角"、第 3 页"夜空"、第 5 页"一只手递出糖果"——
   *     模型只能自己补一个人，补成谁全看运气。
   *   所以这一行不是修辞，它填的是一个真的空。
   * 不传就退回中性词（`孩子`），不是不写那一行：那一行真正管的是
   *   "整本书是同一个人"这条不变式，性别词只是它的一半。
   */
  childWord?: string
  /** 参考图不参与 prompt 文本，它是请求里的另一个字段 */
}

/**
 * 一页的完整 prompt。
 *
 * `scene` 也进 prompt：正文是给耳朵听的，场景是给眼睛看的，两者不一致时
 * 画出来的东西会跟文字对不上（实测过的失败模式：正文说"他游到鲸鱼身边"，
 * 画面只给了个"海边"）。
 */
export function pagePrompt(input: PagePromptInput): string {
  const fix = input.fixNote?.trim()
  const anchor = input.anchorNote?.trim()
  return [
    promptFragmentOf(input.card),
    identityBlock(input.childWord),
    // 这两行的值来自 `story.json`（家长可逐字改），所以包进「」当内容读，
    //   与 `fixNote` / 检索片段那几处同一个手法：引号划出"这是被引用的字"，
    //   而不是"这是给你的要求"。谁说了算由下面那句 `PRECEDENCE_BLOCK` 定。
    `本页画面：「${input.page}」`,
    `情节：「${input.scene}」`,
    `情绪：${MOOD_HINTS[input.mood] ?? input.mood}`,
    // 比对模型上一轮的结论（只有重画那一次才有）。前缀与位置与下面那句同源：
    //   措辞写死在这里，别让调用方各拼一份。
    //   位置在 `fixNote` 之前：两句同时在的时候（家长写了更正、而第 1 次又没过），
    //   人那句是命令、模型这句是诊断，命令排在后面。
    anchor ? `★ 上一版经核对，这几处画得不像，这一版必须照上面的角色描述改对：${anchor}` : '',
    // 家长自己写的那句更正（逐页重画时才有）。前缀写死在这里而不是由调用方拼：
    //   拼在别处的话，这句话的措辞就有了两个家，而它正是模型最该看懂的一句。
    //   位置在页级三项之后、构图与负极清单之前——接在最后的话，
    //   它会与那一长串"避免出现…"抢注意力，而它说的是"上一张哪里错了"，
    //   比那三行通用约束更要紧。
    fix ? `★ 这一版要改掉上一版的问题：${fix}` : '',
    // 它落在最后两个修正块与那两段通用约束之间：往前它读作"上面那些话谁算数"，
    //   往后紧跟着的就是它点名的那两段（构图 / 负极清单）。换位置要重读上面那段 ★。
    PRECEDENCE_BLOCK,
    COMPOSITION_BLOCK,
    NEGATIVE_BLOCK,
  ]
    .filter(Boolean)
    .join('\n')
}

/**
 * 比对模型报出的「这几条不像」→ 一句能喂回出图模型的 `anchorNote`。
 *
 * 它认的是半截话，因为模型回的就是半截话。 真书里录下来的原文
 *   （`.out/web/u/1/books/xiaoman-r1-638df001b4e9/events.jsonl`）是
 *   `["头身比是否一致"]`、`["眼睛是否一致","头发是否一致","头身比是否一致"]` ——
 *   我们发给它核对的是 `checklistOf` 那一条条「头发是否一致：<值>」，
 *   而它把冒号后面丢掉了。所以这里按 `ANCHOR_LABELS` 的槽位名做包含匹配，
 *   匹配上就把卡上那条锚点的原文补回去——补回去的这一步才是这一整件事的意义：
 *   模型上一版错在哪，模型自己说的是"头发"，它需要听到的是"头发：齐耳短发、
 *   右侧别一枚黄色小鸭发卡"。
 * 认不出来的原样带上，不丢。丢掉等于替模型决定"这句没用"，而这一层
 *   没有那个资格（它与"画面审核报的条款 id 一个都不许少"是同一条纪律）。
 * 一条都对不上（或者清单本来就是空的）⇒ `undefined`：没有结论就不编一句结论，
 *   那一轮仍然是"再抽一次签"。这与"画面审核 `unavailable` 时不重画"同一条口径——
 *   缺席不许被读成"我知道该改哪里"。
 *
 * 它不进任何记录，与 `fixNote` 同一条先例：`provenance` 记的是模型、
 *   模板版本、卡版本，而这句是模型的一句诊断。要追"这一版为什么长这样"，
 *   读的是 `events.jsonl` 里那一页前后两条 `consistency`（第一次的 `missedAnchors`
 *   就是这句话的来源），不是清单。
 */
export function anchorNoteOf(card: CharacterCard, missed: readonly string[]): string | undefined {
  const items: string[] = []
  for (const raw of missed) {
    const text = raw.trim()
    if (!text) continue
    // 认得出槽位就补上卡上的原文；认不出就照原样带上
    const anchor = card.anchors.find((item) => text.includes(ANCHOR_LABELS[item.slot]))
    const item = anchor ? `${ANCHOR_LABELS[anchor.slot]}：${anchor.value}` : text
    if (!items.includes(item)) items.push(item)
  }
  return items.length > 0 ? items.join('；') : undefined
}

/**
 * 「整本书就是这个孩子」那一行。见 `PagePromptInput.childWord` 那段（为什么必须有它）。
 *
 * 措辞里的三件事都是冲着实际的坏法写的，不是客套：
 *   · "每一页都是同一个人" —— 守着跨页一致性这条产品定义；
 *   · "哪怕这一页只看得见一部分" —— 第 5 页那种"只有一只手"的构图，
 *     不说这一句，模型会以为这一页可以不画他；
 *   · "不要换性别、不要换发型" —— 这两个是实测里最先跑偏的两样
 *     （比对模型的思考链原话："待审页头发明显是齐肩中长发，不是短发，鬓角也长"）。
 */
function identityBlock(childWord?: string): string {
  const who = childWord?.trim() ? `（${childWord.trim()}）` : ''
  return (
    `主角：上面描述的那个孩子${who}——整本书的每一页都是**同一个人**：` +
    `同一张脸、同一个发型、同一身穿着。哪怕这一页只看得见一部分（一只手、一个背影、` +
    `或只露出半张脸），也要与上面的描述完全一致。不要换性别、不要换发型，也不要画成另一个孩子。`
  )
}

/** 情绪 → 光线与色调的说法。模型不懂 "tender"，但懂"傍晚的暖光，对比压低" */
const MOOD_HINTS: Record<string, string> = {
  calm: '安静的夜晚或柔和室内光，对比低，动作幅度小',
  wonder: '微微仰视的构图，一束光落在新出现的东西上',
  joy: '明亮的整体光，色彩饱和度高一点，人物姿态舒展',
  tense: '压暗一档但不恐怖：阴影柔和、边缘虚，绝不出现尖角与暗色怪物',
  tender: '近距离、暖色、浅景深，两个角色之间留很少的空',
  proud: '略仰角、开阔背景、光从角色身后打过来形成轮廓光',
}

/**
 * 出图尺寸：一页一张 3:2 横版（1536×1024），封面另出 3:4 竖版（见 `COVER_IMAGE_SIZE`）。
 *
 * 2026-10-15 改：原来是 1440×1440 方图、靠居中裁成跨页与封面。改的理由与量法：
 *
 * 1. 3:2 与 3:4 直出实测通过（这条以前写的是"未实测，所以不猜"，现在测了）：
 *    `1536x1024` 与 `1152x1536` 都回来得分毫不差，约 9.5s/张。
 *    命令：对 `/images/generations` 各发一次，再读回 PNG 的 IHDR 宽高比对（不只是看 HTTP 200）。
 * 2. 构图本来就是按跨页写的（见下面的 `COMPOSITION_BLOCK`：主体偏右、左下留出可叠字区），
 *    所以方图裁成 3:2 是先按方构图、再切掉两端——留出的那块会被切走或位移，
 *    正文叠上去就可能压到主体。直出 3:2 才让提示词与成品形状对上。
 * 3. 首页第二屏那本演示书的跨页是 3:2（`public/book/spread-*.webp` 1264×842）、
 *    封面是 3:4（`cover.webp` 848×1130），生成侧现在与它一致。
 *
 * 一口价与尺寸无关（模型.md §4），所以换尺寸不改成本。
 */
export const DEFAULT_IMAGE_SIZE = '1536x1024'

/**
 * 封面尺寸：3:4 竖版，与首页演示书的 `cover.webp`（848×1130）同比例。
 *
 * 封面是单独一次出图，不是从某一页里挑一张——它是第一面，
 *   要能独立回答"这本书讲谁"，而任何一页的跨页图都做不到这件事
 *  （它们的构图是"这一页在发生什么"，而且左下角被正文占着）。
 */
export const COVER_IMAGE_SIZE = '1152x1536'

/**
 * 封面的 prompt。
 *
 * 与页图的区别只有两处，都是有理由的：
 * 1. 不写情节，只写"这个孩子 + 这个名字所指的那件事"。封面上放一个具体情节，
 *    等于用第一页当封面。
 * 2. 画面里照样不放任何文字（书名由 HTML 叠上去）——理由与页图同源
 *    （`docs/cover-art-prompts.md`：中文进图必错字/缺笔），
 *    所以这里明确要求上方留出可以压书名的区域。
 */
export function coverPrompt(input: { card: CharacterCard; title: string }): string {
  return [
    promptFragmentOf(input.card),
    `这是绘本的封面：主角是上面描述的那个孩子，画面要能回答"这本书讲谁"。`,
    // 书名包在《》里本来就带"这是被引用的字"的意味，但书名是模型写的、家长可改
    //   （`PUT /api/books/<id>/story`），所以它与页图那两行同属"会打架而原来没人说谁赢"
    //   的那一类——下面那句 `PRECEDENCE_BLOCK` 就是那次补上的判据（2026-10-20）。
    `书名叫《${input.title}》——**不要把书名画进画面**，但请在画面上方留出一条相对干净的区域，书名会由版式叠在那里。`,
    '构图：主角占画面中部偏下，正对或半侧对镜头，姿态安静；背景是这本书里最标志性的那个场景，但要简化、不要堆细节。',
    PRECEDENCE_BLOCK,
    NEGATIVE_BLOCK,
  ].join('\n')
}
