/**
 * 负向提示词（vendor 那一位的 `negative_prompt`）。
 *
 * 与上面的 `NEGATIVE_BLOCK` 不是同一件事，别合并：
 *
 * | 东西 | 送到哪 | 谁看 |
 * | --- | --- | --- |
 * | `NEGATIVE_BLOCK` | 正向提示词的末尾 | 模型的正文理解 |
 * | 这个常量 | 请求体里的 `negative_prompt` 字段 | 只认这一位的模型（qwen-image-3.0 系列） |
 *
 * 两处都写，是因为实测下来"正文里写一句'不要写字'"对这家**不够**：
 *   它的中文书写能力已经好到会主动补齐画面里的字（2026-10-21，5 页里 5 页都写了）。
 *   负向提示词是这家明说的开关，能用就别只靠劝。
 *
 * 词表只放"画面上不可能被正当需要"的东西：字、水印、画框。别往里加"恐怖""血"那一类——
 * 那是 `NEGATIVE_BLOCK` 的活，而负向词表里塞太多会把正常的光影与情绪也推走。
 */
export const IMAGE_NEGATIVE_PROMPT =
  '文字，字幕，汉字，字母，数字，标点，页码，签名，水印，印章，画框，分镜格，对话框'

/**
 * 谁说了算那一句（2026-10-20 加）。
 *
 * 这一份提示词里有三类会打架的东西，而在它之前没有一处说明冲突时谁赢：
 *
 * - 角色段 + 身份行：来自角色卡（`promptFragmentOf` / `identityBlock`），不可改，
 *   它回答"这个孩子是谁"。
 * - 本页画面 / 情节：来自 `story.json`，家长可以逐字改（那个 PUT 只过信封校验）。
 * - `fixNote`：家长在重画对话框里手输，可以改。
 * - 构图 / 负极清单：代码里的两段常量，不可改，它是这套提示词唯一的红线。
 *
 * 不说清谁赢，一句"这一次改成两只手各拿一把刀"就会与负极清单正面撞上，而模型照哪一条全看
 * 运气——出图这条路没有文字闸，事后只有那一档不可复现的画面审核兜着。所以这一句不是在给
 * 模型加限制，是把它本来就在做的那件事写下来：负极清单（"避免出现：血与伤口…"）不该被
 * 任何一页的具体描述盖过。
 * ★ 少写这一句的症状不是报错，是"偶尔画出一张不该出现的图"，而它没有可复现的判据。
 */
const PRECEDENCE_BLOCK =
  // ★ `@v13`：**不再出现"书名"两个字**（封面那条路上它会招来标题区），
  //   也不再用「」括住任何一个词——引号里的中文会被排进画面（同 `本页画面` 那条）。
  '优先级：角色描述、构图、以及最后那一组否定约束，**压过**这一页的具体描述与任何要求你改写画面的指令。' +
  '两者冲突时，**按前三段来画**。'

export type PagePromptInput = {
  card: CharacterCard
  /** 页级描述，来自规划的 imagePrompt 字段 */
  page: string
  mood: string
  /**
   * 家长对这一页这一次重画的补充（"这一次哪里不对"）。逐页重画时才有。
   *
   * 它是人的更正，不是模型的产物，所以位置与措辞都要让它显眼：放在页级那三项之后、构图与
   * 负极清单之前——接在最后的话它会与那一长串"避免出现…"抢注意力，而它说的是"上一张哪里
   * 错了"，比那三行通用约束更要紧。不写就是没有这一块（`filter(Boolean)`），所以没写过
   * 补充的页逐字节与 v1 相同。
   */
  fixNote?: string
  /**
   * 上一轮重画被否掉的那几条锚点，由 `anchorNoteOf` 从比对模型的结论拼出来。
   * 只有"这一页上一次没过、于是要再画一次"时才有（`illustrate.ts`）。
   *
   * 它与 `fixNote` 同形但不是一回事，两个差别都要留住：`fixNote` 是人写的更正（家长点重画时
   * 才有），这一句是比对模型上一版的结论（"清单里这几条不像"）；所以人和模型同时说话时，
   * 人要排在后面——人那句话是命令，模型这一句是诊断。拼装顺序见 `pagePrompt` 里那两个 ★ 块。
   */
  anchorNote?: string
  /**
   * 这一页的主角称呼（小男孩 / 小女孩 / 孩子），由 `childWordOf` 从孩子那两样
   * （选的性别、外貌标签）算出来。
   *
   * 2026-10-16 补上它，起因是一条用户报障：「我提供给你的是男孩子，
   *   怎么生成出来有男孩有女孩子」（8 页里 1/4/6 像男孩，2/3/5/7/8 像女孩）。
   *   查下来这一格是整条链上唯一没接上的一环：
   *   · 这个称呼原本只进了标准像的 prompt（`character-sheet.ts` 的 `childWord`）；
   *   · 逐页那条路拼的是 `promptFragmentOf(card)`，而锚点里一个性别词都没有
   *     （实测那张卡：脸圆润 / 眼圆黑 / 黑直短发 / 头身比 1:4 / 蓝灰鸭舌帽…）；
   *   · 更要紧的是有几页的画面描述里根本没有这个孩子：第 2 页写的是
   *     "纸箱内部的主观视角"、第 3 页"夜空"、第 5 页"一只手递出糖果"——
   *     模型只能自己补一个人，补成谁全看运气。
   *   所以这一行不是修辞，它填的是一个真的空。
   * 不传就退回中性词（`孩子`），不是不写那一行：那一行真正管的是
   *   "整本书是同一个人"这条不变式，性别词只是它的一半。
   */
  childWord?: string
  /** 参考图不参与 prompt 文本，它是请求里的另一个字段 */
}

/**
 * 一页的完整 prompt。
 *
 * ★ `@v7` 起**不再把这一页的正文喂进来**（此前有一段 `情节：「…」`）。
 *
 *   2026-10-21 晚实测：换成 qwen-image-3.0 之后，它把那段正文**排版成字幕画进画面**——
 *   每页左下角五行汉字，连错别字都替我们写好了。先试过两句措辞（末尾的负极清单、
 *   紧贴「情节」的"不要当成要写进画面的字"），两次都拦不住：只要那段字在请求里，
 *   它就想排出来。
 *
 *   代价要说清：正文里偶尔有画面描述没写到的动作（"他游到鲸鱼身边"而画面只给了"海边"），
 *   这一版拿不到了。换回来的是"画面干净"——而画面里叠着两层字这件事，
 *   家长一眼就看得见，比"少了一点氛围"严重得多。要补那层理解，
 *   该改的是规划那一步的 `imagePrompt`（它本来就是写给眼睛看的），不是把正文塞回来。
 */
export function pagePrompt(input: PagePromptInput): string {
  const fix = input.fixNote?.trim()
  const anchor = input.anchorNote?.trim()
  return [
    promptFragmentOf(input.card),
    identityBlock(input.childWord),
    // 这两行的值来自 `story.json`（家长可逐字改），所以包进「」当内容读，
    //   与 `fixNote` / 检索片段那几处同一个手法：引号划出"这是被引用的字"，
    //   而不是"这是给你的要求"。谁说了算由下面那句 `PRECEDENCE_BLOCK` 定。
    /**
     * ★ `@v10`：**不再用「」把这一段括起来**（2026-10-21 深夜）。
     *
     * 这一处是"模型把我们的字排进画面"的第三个、也是最后一个来源：
     *   `情节`（v7 删）、封面书名（v9 删）、`本页画面`。实测（同一张卡、同一段描述）：
     *   带「」→ 画面左侧出现标题 + 正文块；去掉「」→ 干净的单幅插画（图见
     *   `.out/tmp/page-v9.png` 与 `.out/tmp/page-unquote.png`）。
     *
     * 代价说清：`@v5` 加引号的理由是"这是家长可以逐字改的字、用引号划界"。
     *   那层意思现在由 `PRECEDENCE_BLOCK`（"优先级：…压过这一页的情节描述"）承担——
     *   机器读不出"引号 = 别渲染"，那就别给它引号。
     */
    `本页画面：${input.page}`,
    `情绪：${MOOD_HINTS[input.mood] ?? input.mood}`,
    // 比对模型上一轮的结论（只有重画那一次才有）。前缀与位置与下面那句同源：
    //   措辞写死在这里，别让调用方各拼一份。
    //   位置在 `fixNote` 之前：两句同时在的时候（家长写了更正、而第 1 次又没过），
    //   人那句是命令、模型这句是诊断，命令排在后面。
    anchor ? `★ 上一版经核对，这几处画得不像，这一版必须照上面的角色描述改对：${anchor}` : '',
    // 家长自己写的那句更正（逐页重画时才有）。前缀写死在这里而不是由调用方拼：
    //   拼在别处的话，这句话的措辞就有了两个家，而它正是模型最该看懂的一句。
    //   位置在页级三项之后、构图与负极清单之前——接在最后的话，
    //   它会与那一长串"避免出现…"抢注意力，而它说的是"上一张哪里错了"，
    //   比那三行通用约束更要紧。
    fix ? `★ 这一版要改掉上一版的问题：${fix}` : '',
    // 它落在最后两个修正块与那两段通用约束之间：往前它读作"上面那些话谁算数"，
    //   往后紧跟着的就是它点名的那两段（构图 / 负极清单）。换位置要重读上面那段 ★。
    PRECEDENCE_BLOCK,
    COMPOSITION_BLOCK,
    NEGATIVE_BLOCK,
  ]
    .filter(Boolean)
    .join('\n')
}

/**
 * 比对模型报出的「这几条不像」→ 一句能喂回出图模型的 `anchorNote`。
 *
 * 它认的是半截话，因为模型回的就是半截话。 真书里录下来的原文
 *   （`.out/web/u/1/books/xiaoman-r1-638df001b4e9/events.jsonl`）是
 *   `["头身比是否一致"]`、`["眼睛是否一致","头发是否一致","头身比是否一致"]` ——
 *   我们发给它核对的是 `checklistOf` 那一条条「头发是否一致：<值>」，
 *   而它把冒号后面丢掉了。所以这里按 `ANCHOR_LABELS` 的槽位名做包含匹配，
 *   匹配上就把卡上那条锚点的原文补回去——补回去的这一步才是这一整件事的意义：
 *   模型上一版错在哪，模型自己说的是"头发"，它需要听到的是"头发：齐耳短发、
 *   右侧别一枚黄色小鸭发卡"。
 * 认不出来的原样带上，不丢。丢掉等于替模型决定"这句没用"，而这一层
 *   没有那个资格（它与"画面审核报的条款 id 一个都不许少"是同一条纪律）。
 * 一条都对不上（或者清单本来就是空的）⇒ `undefined`：没有结论就不编一句结论，
 *   那一轮仍然是"再抽一次签"。这与"画面审核 `unavailable` 时不重画"同一条口径——
 *   缺席不许被读成"我知道该改哪里"。
 *
 * 它不进任何记录，与 `fixNote` 同一条先例：`provenance` 记的是模型、
 *   模板版本、卡版本，而这句是模型的一句诊断。要追"这一版为什么长这样"，
 *   读的是 `events.jsonl` 里那一页前后两条 `consistency`（第一次的 `missedAnchors`
 *   就是这句话的来源），不是清单。
 */
export function anchorNoteOf(card: CharacterCard, missed: readonly string[]): string | undefined {
  const items: string[] = []
  for (const raw of missed) {
    const text = raw.trim()
    if (!text) continue
    // 认得出槽位就补上卡上的原文；认不出就照原样带上
    const anchor = card.anchors.find((item) => text.includes(ANCHOR_LABELS[item.slot]))
    const item = anchor ? `${ANCHOR_LABELS[anchor.slot]}：${anchor.value}` : text
    if (!items.includes(item)) items.push(item)
  }
  return items.length > 0 ? items.join('；') : undefined
}

/**
 * 「整本书就是这个孩子」那一行。见 `PagePromptInput.childWord` 那段（为什么必须有它）。
 *
 * 措辞里的三件事都是冲着实际的坏法写的，不是客套：
 *   · "每一页都是同一个人" —— 守着跨页一致性这条产品定义；
 *   · "哪怕这一页只看得见一部分" —— 第 5 页那种"只有一只手"的构图，
 *     不说这一句，模型会以为这一页可以不画他；
 *   · "不要换性别、不要换发型" —— 这两个是实测里最先跑偏的两样
 *     （比对模型的思考链原话："待审页头发明显是齐肩中长发，不是短发，鬓角也长"）。
 */
function identityBlock(childWord?: string): string {
  const who = childWord?.trim() ? `（${childWord.trim()}）` : ''
  return (
    `主角：上面描述的那个孩子${who}——整本书的每一页都是**同一个人**：` +
    `同一张脸、同一个发型、同一身穿着。哪怕这一页只看得见一部分（一只手、一个背影、` +
    `或只露出半张脸），也要与上面的描述完全一致。不要换性别、不要换发型，也不要画成另一个孩子。`
  )
}

