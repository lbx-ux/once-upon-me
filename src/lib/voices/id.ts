/**
 * voices/id.ts —— 音色 id 这一条**唯一的**判据
 *
 * ★ 为什么单独一个文件：这条判据本来有**两个家**，而它们已经漂了。
 *   `book-api.ts` 里是 `MAX_VOICE_ID = 64`，`rerun-api.ts` 里是**硬写的 `64`**
 *   —— 同一个数写两遍，改一处不会想到另一处（这正是 docs/known-tradeoffs.md 那条"两处手写的数
 *   会各自漂移"）。谁再加第三个消费者，改这里一处就够。
 *
 * ★★ 64 这个数**是错的，而且是量出来的**（2026-10-18）
 * ---------------------------------------------------------------------------
 * 用户报：「在做绘本的时候，选择自己生成的声音就会报错，选择其他声音就不会」，
 * 屏幕上那句话是「音色 id 太长了（64 字以内），多半是别的字段串进来了」。
 *
 * 拿真 key 建了一条真音色量了一下（`.out/voice-id-shape.mts`，建完**立刻 release**）：
 *
 *   voice_id = qwen-audio-3…f14f，**68 字**
 *   拆开是 `qwen-audio-3.0-tts-flash`(24) + `-xiaozhujue-`(12) + 32 位随机
 *   里面没有空格、引号、花括号、中文 —— **它是一条完全正常的 id，只是比 64 长 4 个字**
 *
 * 也就是说那 64 是当初**猜**的（注释里写的理由"写长了必然是别的字段串进来了"，
 * 是在解释这个猜测，不是在记录一次测量）。它拦下的恰恰是用户自己录的那一条，
 * 而预置那两个（`longjielidou_v3.6` 17 字、`longanlingxi` 12 字）永远碰不到它
 * —— 所以这个 bug 只在"用自己克隆的音色"那条路上出现，正是用户描述的形状。
 *
 * ★ 现在的上界取 **128**，不是又猜一个：后端 `voices.voice_id` 就是
 *   `VARCHAR(128)`（`server/src/main/resources/db/schema.sql`）—— 两边取同一个数，
 *   于是"界面放行、库里放不下"这种错法不会出现。
 *
 * ★ 而"别的字段串进来了"这件事**没有不管**，只是换了判据：**看形状，不看长度**。
 *   串了字段的字符串里一定会出现空格、引号、花括号、斜杠或中文，
 *   而厂商 id 的字符集是 `[A-Za-z0-9._-]`。长度只做兜底。
 */

/**
 * 音色 id 的长度上界。★ 与后端 `voices.voice_id VARCHAR(128)` 同一个数
 * （实测的厂商 id 是 68 字，见文件头）
 */
export const MAX_VOICE_ID = 128

/**
 * 厂商 id 允许出现的字符。
 * ★ 它就是"是不是串了字段"这条判断**真正的**判据：一个串了字段的字符串
 *   （`{"voiceId":"…"}`、`我的声音 小宇`、`https://…`）必然带空格/引号/花括号/斜杠/中文。
 *   实测的两个预置与一条真克隆出来的 id 都在这个字符集里。
 */
const VOICE_ID_SHAPE = /^[A-Za-z0-9._-]+$/

/**
 * 这一条音色 id 有没有问题。没问题回 `null`（调用方的 `problems` 直接 push 它）。
 * ★ 空串**不是**问题：它表示"这一本不配音"，与"没填"是两件事（见 `book-api.ts` 的调用处），
 *   所以这里不拦它。
 */
export function voiceIdProblem(voiceId: string): string | null {
  if (voiceId === '') return null
  if (voiceId.length > MAX_VOICE_ID) {
    return `音色 id 太长了（${MAX_VOICE_ID} 字以内，这一段是 ${voiceId.length} 字）`
  }
  if (!VOICE_ID_SHAPE.test(voiceId)) {
    return '音色 id 里出现了不该有的字符（空格、引号、花括号、中文之类）——多半是别的字段串进来了'
  }
  return null
}
