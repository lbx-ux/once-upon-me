/**
 * 重试提示的那一段尾巴：把上一轮的具体问题贴回请求里。
 *
 * 它是通过率的决定因素之一（`plan.ts` 文件头第 2 条）：原样重发一次是拿钱换同样的输出。
 * 两个调用方（独读版的一次性路径、共读版的分段展开）共用这一份——各写一句的话，
 * 迟早会出现一条路上带反馈、另一条路上只是重抽。
 */

/**
 * `noun` 是"别把什么重写一遍"里的那个宾语。
 *
 * 它必须由调用方给：独读版重试的是一整张故事表（"别重写整个故事"），
 * 而共读版展开重试的只是某一段（"别重写整份提纲"）——说反了，模型会去动它不该动的部分。
 */
export function withFeedback(user: string, failures: readonly string[], noun = '整个故事'): string {
  return [
    user,
    '',
    `【上一次你的输出不合格，问题如下——只改这些问题，别重写${noun}】`,
    failures[failures.length - 1] ?? '',
    '只输出 JSON。不要解释，不要围栏之外的任何字。',
  ].join('\n')
}
