/**
 * avatars.ts —— 站点那**唯一一个**默认头像
 *
 * ★ 它**不是用户数据**。2026-10-17 用户把工单 08 那六个可选头像整条否掉：
 *   「算了吧，只提供一个默认头像，然后用户不可以切换，生成一个头像，符合当前项目的，
 *   现在的这个蓝色的不好看」。所以这里没有"挑一个"、没有白名单、没有认不出的兜底
 *   ——一个常量就够了，而**认不出的 id 这条路径随之消失**（原来它是这一份里最大的
 *   一段，见下面那条历史）。
 *
 * ## 画面是什么，谁画的（2026-10-18，盘上现在这张）
 *
 * 一个背对着的孩子盘腿坐着，捧着一本摊开的书，书页上飘着星星、云和月亮；整幅是一张
 * 水彩。**这画是用户自己给的**（原话「把系统提供的默认头像换成这个」），不是本站那条
 * 出图通路生成的——所以这一份里没有提示词可调，`scripts/make-default-avatar.mts`
 * 的 `--from=` 那一条路只做"裁 + 缩 + 落"。
 *
 * ★ **"谁画的"要写进来，因为它是这一格唯一没被量过的那一维**：在它之前，v3 与 v4
 *   两版的读数**全部过了判据**，两次都被用户看一眼否掉（v3 的评语是「想粑粑一样」）。
 *   能证伪的都证伪完了，剩下的分歧是"这是不是我们要的那张画"——**那个只有人能回答**。
 *   所以这一版换的不是提示词，是出图的人。上面这一句是这一份里最该被记住的一条。
 *
 * ## 文件名跟着画面走
 *
 * 它叫 `dushu`（「读书」），因为画面就是一个在看书的孩子。**改名与换图必须同时做**：
 * 上一版叫 `yun.webp`（一朵云，本站第一本样书《小宇的云》里那个东西）——
 * 把那个名字留给一张看书的画，比不写注释更坏，名字是一句没人会去核对的断言。
 *
 * ## 为什么这张暖色的画，坐在一屏冷色里（那两条判据没变）
 *
 * 工单 15 当时让六张头像跟着个人主页那一屏转**冷**（底 `--pf-paper`、记号
 * `--pf-accent`）。现在反过来了，两条判据都要留着：
 *
 * 1. **冷底 + 冷记号在那一屏上等于看不见。** 头像坐在那一屏的淡蓝里，而那一屏的底
 *    （`.pfb` 那三团光晕）与次级文字也是同一族的蓝——用户说的"这个蓝色的不好看"，
 *    量出来就是**三个层次全是同一支色相**。
 * 2. **本站那条法律本来就写着暖色该在这儿**（`globals.css` 的 `:root`）：
 *    **「冷的是光，暖的是物件。」** 头像与角色墙那块裱照片的 mat、手写标签是同一类
 *    东西——一个被拿在手里的**物件**，不是光。
 *    ★ 这一张上的暖**不是照着令牌配的**：奶油色的纸底、赭黄的毛衣、棕的头发，
 *      是画本身就落在暖的一侧；它里面也有蓝（书页上的星、裤子），但那是**水彩里的
 *      蓝**，压在那张暖纸上——跟"整块冷底 + 冷记号"是两回事，后者才是当时被否掉的。
 *      所以这条法律撑得住，而撑住它的**不是**这张图用了哪个令牌（它一个都没用）。
 *    ★ 上一版这里写的是"用全站那颗陶土橙 `--accent`(#c2410c) 起笔"——那句话随着
 *      这张画一起作废了，它当时描述的是照着 `:root` 令牌生成的那张云。
 *    ★ 这不违背后端那一屏"整体转蓝"的指定：转的是**光**（页面底、描边、次级文字），
 *      暖色在这条法律里的身份本来就是物件。
 *
 * ## 图是怎么来的（可复现）
 *
 * ```bash
 * node scripts/make-default-avatar.mts --from=.out/avatar-src/source.webp
 * ```
 *
 * 原图 1024×1024 留在 `.out/avatar-src/`（gitignored）——**原图不进 `public/`**，
 * 那是 `avatars.test.ts` 里那条 256×256 在挡的事：`public/` 会进公开仓库的历史。
 * 裁到哪一块是**量出来的**，不是拍的 `(512,512)`：沿 1440 条射线从外往里扫出那圈
 * 手绘蓝环，再做一次 Kasa 圆拟合，解出圆心 (513.5, 507.9)。`half=380` 取的是
 * **环内**，所以这一张上**看不到那圈蓝环**，只有孩子和书。
 *
 * ★ 这个取舍有代价，两个显示尺寸不是一回事：**92px 那格**（`.pf__avatar`）里
 *   孩子与书读得很清楚；**20px 那格**（`.shell__avatar`，侧栏）读出来是一个
 *   深色头的、小孩形状的小人。要让它读成"一枚带蓝边的圆"而不是"一个小孩"，
 *   换成 `--half=420` 把环带进来——310 / 380 / 420 三个半边长的读数表
 *   （圆内非纸 63.2% / 44.6% / 44.9%，圆内蓝 0.35% / 0.23% / 1.37%）在脚本的
 *   `CROP` 上面，420 那圈环被 `border-radius:50%` 切出的不均匀边也写在那里。
 *
 * ## 那条历史（留着，因为它是"两处真相"的学费）
 *
 * 原来这一份里有一个 `avatarSrc(id)`：认得出来给 `/avatars/<id>.svg`，认不出来给
 * `null`，调用方照 `null` 画一个"这里空着"的圈。它守的是一条对**用户数据**才成立的
 * 规矩——**绝不回落成某一个默认头像**，因为那样一来"我以外的人看起来都变成了同一个
 * 头像"，而那种错没人会去查。现在头像不再是用户数据，"同一个人人一样"是**指定的
 * 结果**，那条规矩连同它守的那段代码一起没有了。⭐ **下一批"可选头像"回来时，
 * 那三段（白名单 / 认不出给 null / 不回落）必须一起回来。**
 */

