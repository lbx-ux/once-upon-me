/**
 * avatars.ts —— 几个**默认头像**，用户在里头挑一个（工单 08）
 *
 * ★ 不做上传（用户 2026-10-16 的原话：「头像上传就免了吧，系统给用户几个默认头像，
 *   用户可以在那个里面切换」）。所以这一份是**静态资产**，不是一条上传通路——
 *   服务器上因此没有"用户上传的文件"要管，也没有它的体积与内容风险。
 *
 * ★ 色值写死在 SVG 里，出处是 `globals.css` 的 `:root`：
 *
 *     --pf-paper    #e8f0f6   头像底。★ **2026-10-17 换的**：原来是 `--card-paper`
 *                             （#f7efe3，暖相纸），用户要求个人主页那一屏改成蓝的，
 *                             于是这一屏另开了一组令牌（`--pf-*`，理由写在 globals.css
 *                             那一段里），头像跟着换到同一颗冷色。它与 `--ink-muted`
 *                             的对比度 4.63:1（原来那版是 4.67:1），同一个空圈图形
 *                             换底之后仍然过线。
 *     --pf-accent   #427294   记号本身。同色相压深一档的蓝，**5.16:1**——参考稿那一版
 *                             (#4a7fa7) 是 4.28:1，做 12px 标签的字色差一点没过 4.5。
 *     --ink         #17171d   最重的那一笔
 *     --ink-muted   #6b6a74   次重的那一笔
 *     --paper       #f4f8f9   高光/留白（云、月牙的缺口）
 *
 *   ★ **为什么不能写 `var(--x)`**：这几个文件是被 `<img src>` 引的，那是一份**独立文档**，
 *     拿不到页面的自定义属性——写 `var()` 的结果是那几个形状**什么都不画**（而且不报错）。
 *     所以改配色时这里要跟着改，这是这一份文件唯一一处要人工同步的地方，写在最上面。
 *     ★ 这条同步**有机器判据**：`avatars.test.ts` 里有一张白名单，写进去一个
 *       不在令牌表里的颜色就会红。所以照着上面这五行改，别自己调一个"看着更顺"的。
 *   ★ 同一条理由的另一半：**不进 `scripts/make-webp.py` 那条流水线**。那是给位图重编码用的
 *     （封面、场景），而这几个是矢量，缩到 32px 也不糊——重编码只会把它变成一张
 *     更模糊的位图，还多一个要跟着 SVG 改的产物。
 *     ★ 但如果用户按工单 15 出的**位图**替换掉这六个（他要重新生成头像），
 *       这半条理由就不成立了——那时候它们该进那条流水线。见那份工单的「怎么交付」。
 *
 * ★ **两边不各存一份白名单**（工单 08 的原话）：后端只存一个 id，形状是
 *   `^[a-z0-9_-]{1,32}$`（见 `AccountRules.requireAvatarId`）。前端认不出的 id
 *   **一律退回"头像空着"那个圈**，而不是报错、也不是回落成某一个默认头像——
 *   后者的症状是"我以外的人看起来都变成了同一个头像"，而那种错没人会去查
 *   （`auth/state.ts` 的 `parseUser` 对 `avatar` 就是这么宽的：只要是个字符串就收）。
 *
 * ★ 形状的来处：**云**与**纸船**直接取自本站那本演示书（"小宇的云"里，云变成了恐龙的背、
 *   又变成一条船的肚子）。这不是装饰性的巧合——一个默认头像画的是"这个站的第一个故事里
 *   出现过的东西"，比一个通用的抽象图形更说得清它属于哪儿。其余四个是同一支笔下的
 *   日常物件（太阳 / 蒲公英 / 叶子 / 月亮）。
 */

export type AvatarOption = {
  /** 存进库里的就是这一个。★ 与 `AccountRules.requireAvatarId` 那个正则逐字一致 */
  id: string
  /** 界面上显示的名字。★ 是**这个记号是什么**，不是"头像 1/2/3"：读屏念出来要有意义 */
  name: string
}

/** 六张，`public/avatars/<id>.svg`。★ 次序是这一排在界面上从左到右的次序 */
export const AVATARS: AvatarOption[] = [
  { id: 'yun', name: '云' },
  { id: 'chuan', name: '纸船' },
  { id: 'taiyang', name: '太阳' },
  { id: 'pugongying', name: '蒲公英' },
  { id: 'yezi', name: '叶子' },
  { id: 'yueliang', name: '月亮' },
]

/**
 * 一个 id（可能是任何东西：老数据、手改过的库、别的版本写进去的）→ 头像的地址。
 * **认不出就是 `null`**——调用方照 `null` 画那个空的圈（见文件头）。
 *
 * ★ 返回的是**站内绝对路径**，不是 `<img src>` 的拼装结果：调用方直接把它交给 `src`。
 *   ★ 绝不写成 `new URL(id, base)` 那种拼法——本机在一个 fake-IP 代理后面，
 *     出图是两跳，拼地址会拼到代理那儿去（README 那条踩坑）。
 */
export function avatarSrc(id: string): string | null {
  const found = AVATARS.find((item) => item.id === id.trim())
  return found ? `/avatars/${found.id}.svg` : null
}

/** 这个 id 认不认得。挑头像那一排用它标出"当前是哪一个" */
export function isKnownAvatar(id: string): boolean {
  return avatarSrc(id) !== null
}

