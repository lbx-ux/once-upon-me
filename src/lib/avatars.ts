/**
 * avatars.ts —— 站点那**唯一一个**默认头像
 *
 * ★ 它**不是用户数据**。2026-10-17 用户把工单 08 那六个可选头像整条否掉：
 *   「算了吧，只提供一个默认头像，然后用户不可以切换，生成一个头像，符合当前项目的，
 *   现在的这个蓝色的不好看」。所以这里没有"挑一个"、没有白名单、没有认不出的兜底
 *   ——一个常量就够了，而**认不出的 id 这条路径随之消失**（原来它是这一份里最大的
 *   一段，见下面那条历史）。
 *
 * ## 为什么是暖色，而它所在的那一屏是冷的
 *
 * 工单 15 当时让六张头像跟着个人主页那一屏转**冷**（底 `--pf-paper`、记号
 * `--pf-accent`），理由是"别成为不在调子里的东西"。现在反过来了，两条判据都要留着：
 *
 * 1. **冷底 + 冷记号在那一屏上等于看不见。** 头像坐在那一屏的淡蓝里，而那一屏的底
 *    （`.pfb` 那三团光晕）与次级文字也是同一族的蓝——用户说的"这个蓝色的不好看"，
 *    量出来就是**三个层次全是同一支色相**。
 * 2. **本站那条法律本来就写着暖色该在这儿**（`globals.css` 的 `:root`）：
 *    **「冷的是光，暖的是物件。」** 头像与角色墙那块裱照片的 mat、手写标签是同一类
 *    东西——一个被拿在手里的**物件**，不是光。放在暖相纸上、用全站那颗陶土橙
 *    `--accent`(#c2410c) 起笔，它才**是一张本站封面的一小块**，而不是贴上去的冷色图标。
 *    ★ 这不违背后端那一屏"整体转蓝"的指定：转的是**光**（页面底、描边、次级文字），
 *      暖色在这条法律里的身份本来就是物件。
 *
 * ## 为什么是一朵云
 *
 * 六张里唯一一张是**本站自己要讲的第一个故事里出现过的东西**——
 * `public/demo` 那本「小宇的云」（云先变成恐龙的背，又变成一条船的肚子）。
 * 拿一个当站点门面时，这个理由压过"哪个剪影更好看"。云的横向团块在 22px 的圆里
 * 也读得出来，而它边缘那圈水彩晕开的样子正是那六个线描 SVG 缺的那件事。
 *
 * ## 图是怎么来的（可复现）
 *
 * `node scripts/make-default-avatar.mts` —— 用本站自己那条出图通路
 * （`wan2.7-image`，`.env.local`）出两张候选并拼一张按真尺寸裁圆的对照表，
 * `--apply=<行号>` 落 `public/avatars/yun.webp`（256×256，webp）。
 * ★ 第一版提示词**实测没过**（两张都出了一整幅有小孩的风景画），改了三处才过；
 *   那三处与判据都写在脚本的文件头里，**别再照抄工单 15 那六条提示词**——
 *   它们是写给另一个图像模型的。
 *
 * ## 那条历史（留着，因为它是"两处真相"的学费）
 *
 * 原来这一份里有一个 `avatarSrc(id)`：认得出来给 `/avatars/<id>.svg`，认不出来给
 * `null`，调用方照 `null` 画一个"这里空着"的圈。它守的是一条对**用户数据**才成立的
 * 规矩——**绝不回落成某一个默认头像**，因为那样一来"我以外的人看起来都变成了同一个
 * 头像"，而那种错没人会去查。现在头像不再是用户数据，"同一个人人一样"是**指定的
 * 结果**，那条规矩连同它守的那段代码一起没有了。⭐ **下一批"可选头像"回来时，
 * 那三段（白名单 / 认不出给 null / 不回落）必须一起回来。**
 */

