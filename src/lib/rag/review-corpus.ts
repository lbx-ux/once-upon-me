/** 见文件头第一节：两档的分工 */
export type ClauseDetect = 'lexicon' | 'semantic'

/**
 * 命中之后怎么处置。
 *
 * - `rewrite`：**先让它改**——带反馈重试，改几版还是不行才拒发。
 * - `block`：**当场拒发，不重试**。只给两类：自伤与危险示范的可模仿示范。
 *   理由是它们**最不能落到孩子眼睛里**，而"让模型看着这段内容再改一遍"
 *   本身就是一次多余的接触。
 *
 * ★ 两者都不能"静默放过"——`errors.ts` 那条「显式失败，无静默降级」在这里的落点。
 */
export type ClauseDisposition = 'rewrite' | 'block'

export type ReviewClause = {
  /** `R-01`。★ 它就是`判据 5` 要的那个"具体到哪一条" */
  id: string
  category: ClauseCategory
  /** 条款原文：给人读、也给将来那一档模型读 */
  text: string
  detect: ClauseDetect
  disposition: ClauseDisposition
  /**
   * 词表。`detect === 'lexicon'` 时必有，否则**不写**（不是空数组——
   * 空数组会被读成"有词表但没词"，那是一件不同的事）。
   */
  lexicon?: readonly string[]
}

