/**
 * review-corpus.ts —— ③ 审核条款：**代码即语料**（spec §三）
 *
 * 这一份不是从任何外部数据来的，是我们**自己写的**：条目来自 `prompts/story-plan.ts`
 * 的 `RED_LINES`（那三行提示词里的红线），加上适龄与"说教"那两条。
 * 写成代码而不是一份 JSON，理由与仓库里其它语料一样：
 * 它要能进 `pnpm test`、能带类型、改一条就是一个 diff。
 *
 * ---------------------------------------------------------------------------
 * ## 一、两档，别混：`lexicon` 是判据，`semantic` 不是
 *
 * | `detect`     | 怎么判                     | 能不能当判据                     |
 * | ------------ | -------------------------- | -------------------------------- |
 * | `lexicon`    | 词表命中（确定性、可复现） | **能**——同一份输入永远同一个结论 |
 * | `semantic`   | 交模型读（一句话或一段）    | **不能**——它是"疑似"，不是"违规" |
 *
 * ★ 这一栏（评分表 #5「内容过滤与兜底机制」）的验收押在 `lexicon` 那一档上，
 *   理由就是**可复现**：工单 05 的判据是"10 条越线全部拦下 + 96 段真样书零误拦"，
 *   而只要模型在环里，这两个数第二天就会变。
 *   `semantic` 那几条**留着但今天不跑**（`review.ts` 只认 `lexicon`），
 *   它们的用处是：把"这一条要靠模型"这件事**写进语料**，而不是让它活在某个人的记忆里。
 *
 * ## 二、★ 词表是**下界**，不是覆盖——这一条必须说在明处
 *
 *   词表能抓的是**写得明明白白的那些**。它抓不到：
 *   · **谐音与拼音**（"丝"、"死翘翘"、"si"）
 *   · **委婉说法**（"再也不回来了"、"睡着了没醒"——死亡那一条的常见写法）
 *   · **外文与 emoji**（"rip"、"🩸"）
 *   · **没有脏字的吓人**（一句"门后面有东西在等她"一个红线词都不含）
 *
 *   ★ 所以**不许**在任何地方（代码注释、文档、答辩）说"我们的内容过滤覆盖了红线"。
 *     能说的是：「词表命中的一律拦下，且这一批词是**可枚举、可复核**的；
 *     剩下的那几类**今天没有判据**」。工单 05 的判据里有一条**故意用谐音绕过**的
 *     反例，它**预期会漏**——那条不是失败，是把这道闸的边界钉在纸上。
 *
 * ## 三、为什么有些词**单字不收**
 *
 *   单字歧义多：`丑`（丑小鸭）、`鬼`（鬼点子）、`砍`（砍柴）。收进来会让
 *   "12 本人工写过的适龄样书"里冒出误拦——而**误拦的代价与漏拦一样大**
 *   （这个项目在"空值算不算错"那一节付过假拦的学费：一本正常的书被拦下来，
 *   家长看到的是"生成失败"）。
 *   所以能收双字词的都收双字，单字只在**它没有第二种意思**时才收（`死`、`血`）。
 *   ★ 这条判断的验证方式不是"我觉得"，是拿 96 段真样书跑一遍（工单 05 的脚本）。
 */

export const CLAUSE_CATEGORIES = [
  '恐怖',
  '暴力',
  '死亡',
  '自伤',
  '歧视',
  '危险示范',
  '说教',
  '适龄',
] as const
export type ClauseCategory = (typeof CLAUSE_CATEGORIES)[number]

/** 见文件头第一节：两档的分工 */
export type ClauseDetect = 'lexicon' | 'semantic'

/**
 * 命中之后怎么处置。
 *
 * - `rewrite`：**先让它改**——带反馈重试，改几版还是不行才拒发。
 * - `block`：**当场拒发，不重试**。只给两类：自伤与危险示范的可模仿示范。
 *   理由是它们**最不能落到孩子眼睛里**，而"让模型看着这段内容再改一遍"
 *   本身就是一次多余的接触。
 *
 * ★ 两者都不能"静默放过"——`errors.ts` 那条「显式失败，无静默降级」在这里的落点。
 */
export type ClauseDisposition = 'rewrite' | 'block'

export type ReviewClause = {
  /** `R-01`。★ 它就是`判据 5` 要的那个"具体到哪一条" */
  id: string
  category: ClauseCategory
  /** 条款原文：给人读、也给将来那一档模型读 */
  text: string
  detect: ClauseDetect
  disposition: ClauseDisposition
  /**
   * 词表。`detect === 'lexicon'` 时必有，否则**不写**（不是空数组——
   * 空数组会被读成"有词表但没词"，那是一件不同的事）。
   */
  lexicon?: readonly string[]
}

