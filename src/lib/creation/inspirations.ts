/** 抽一张牌的结果。★ 纯函数：牌堆不改，回一份新的（调用方存哪一份是它的事） */
export type Draw = {
  /** 抽到的索引，指向 `INSPIRATION_POOL` */
  index: number
  /** 剩下的牌。空了就是空了，下一次抽它自己会重洗 */
  deck: number[]
}

/**
 * 从这副牌里抽下一张。
 *
 * 发牌而不是"每次随机一个下标"，是为了一轮之内不重复：
 *   真随机会连着给同一条（用户看到的是"这颗按钮坏了"，不是"运气"）。
 *   牌空了就重洗——但重洗后的第一张不会等于上一次抽的那一张：
 *     换副牌那一瞬间是唯一还可能撞车的地方，而它恰好出现在用户连按的时候。
 *
 * `rand` 是注进来的（默认 `Math.random`）。测试靠它把"抽了 72 次"这件事
 *   变成可复现的断言，而不是靠统计（统计要跑很多次，还会偶发地红）。
 */
export function drawInspiration(
  deck: readonly number[],
  last: number,
  rand: () => number = Math.random,
): Draw {
  let pool = deck
  if (pool.length === 0) {
    pool = shuffled(INSPIRATION_POOL.length, rand)
    // 换副牌的第一张不能是刚抽过的那一张。★ 换到第二位而不是重抽一次：
    //   重抽会把"第一张"变成一个循环（rand 注入不进去的写法），换位只动两张牌
    if (pool.length > 1 && pool[0] === last) {
      pool = [pool[1] as number, pool[0] as number, ...pool.slice(2)]
    }
  }
  const index = pool[pool.length - 1] as number
  return { index, deck: pool.slice(0, -1) }
}

/** Fisher–Yates。★ 不回 `INSPIRATION_POOL` 本身：一副牌只有一份、抽一张少一张 */
function shuffled(count: number, rand: () => number): number[] {
  const out = Array.from({ length: count }, (_, i) => i)
  for (let i = out.length - 1; i > 0; i--) {
    // `rand()` 约定落在 [0, 1)，但 `min` 兜一下：注入的 rand 回 1 时不该越界取到 undefined
    const j = Math.min(i, Math.floor(rand() * (i + 1)))
    const swap = out[j] as number
    out[j] = out[i] as number
    out[i] = swap
  }
  return out
}
