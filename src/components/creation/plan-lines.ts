/**
 * plan-lines.ts —— 「正在编故事」那一段轮着播的几句话（纯数据，无 React）
 *
 * 2026-10-18 用户原话：「这个编故事和用户一点都没有互动感，就直接说正在编故事，
 *   这个地方优化一下，哪怕把字体变成橙色呢」。在那之前这一屏编故事的几分钟里，
 *   画桌上方那一行一动不动地写着"正在编故事…"——一句话，没有第二件事发生。
 *
 * 那几句话的纪律与工作台那几件活是同一条（`studio/wait-copy.ts` 的文件头）：
 *   只说"还在办"，不说"办到哪儿了"。
 *   编故事这一趟在浏览器这边是一次性回包（`plan-ready` 之前拿不到任何中间消息，
 *   引擎那边一次 `text.stream` 拿到整张故事表），所以这一屏不许出现百分比、秒数、
 *   也不许说"已经写了 6 页"——那三个数我们一个都没有。可以说的是这件活在做什么：
 *   想开头、分页、给每一页想画面。那三句是真话，而且它们不承诺任何时刻。
 *   这一条有机器版：`plan-lines.test.ts` 断言这几句里不出现数字与百分号。
 *
 * 为什么它值得单独一个文件（而不是写在 `Desk.tsx` 里）：与 `studio/wait-copy.ts`
 *   同一个理由——能被 node 钉住的东西不该住在组件里。这里的纪律是"不许出现数字"，
 *   而那种东西写在 JSX 旁边的注释里，下一刀改文案的人顺手就会破坏它。
 *   （★ 那四句的读者只有一个：`Desk` 编故事那一段；`useRotatingLine` 负责播。）
 */

/**
 * 编故事那几分钟轮着说的四句。
 *
 * 顺序是有讲究的：从"想开头"到"分页"到"给每一页想画面"，是这一趟活的自然顺序，
 *   而最后一句是安抚（"还在写"），摆在最后是因为它最像"快好了"——
 *   实测（工单 01 的收口记录）规划这一趟 12 个主题里跑过 2 次重写，
 *   所以不能每一句都像马上要结束。
 *
 * 四句都不含任何时刻、页数、百分比；也不出现"还剩""马上"这类承诺。
 *   "一小会儿"是唯一一个时间感的词，它与工作台那四句里那一句是同一个说法
 *   （同一批文案，别在这里换一个"稍等片刻"）。
 */
