/**
 * plan-lines.ts —— 「正在编故事」那一段说的话（纯数据，无 React）
 *
 * 2026-10-18 用户原话：「这个编故事和用户一点都没有互动感，就直接说正在编故事，
 *   这个地方优化一下，哪怕把字体变成橙色呢」。在那之前这一屏编故事的几分钟里，
 *   画桌上方那一行一动不动地写着"正在编故事…"——一句话，没有第二件事发生。
 *
 * 那几句话的纪律与工作台那几件活是同一条（`studio/wait-copy.ts` 的文件头）：
 *   只说"还在办"，不说"办到哪儿了"。**它们仍然是这一条纪律**，因为它们是
 *   **第一个字到达之前**说的话——那一刻我们真的什么都还没有。
 *   可以说的是这件活在做什么：想开头、分页、给每一页想画面。那三句是真话，
 *   而且它们不承诺任何时刻。这一条有机器版：`plan-lines.test.ts` 断言这几句里
 *   不出现数字与百分号。
 *
 * ★ 2026-10-21（工单 D-04）：这一段话的**前提**变了，所以下面多一个函数。
 *
 *   原来这里写着「编故事这一趟在浏览器这边是一次性回包（`plan-ready` 之前拿不到
 *   任何中间消息），所以这一屏不许出现百分比、秒数、也不许说'已经写了 6 页'
 *   —— 那三个数我们一个都没有」。在 2026-10-21 之前那句话是**真的**：
 *   `plan.ts` 的 `onDelta`、`providers/openai-text.ts` 的 `stream()`、
 *   `engine/plan-stream.ts` 的 `readPlanProgress` 三件都在、都有测试，
 *   而 `src/app/**` 一处都没传——于是"故事正在一页页写出来"这个交互
 *   在线上一次都没跑过，故事是在 `plan-ready` 那一刻整张出现的。
 *
 *   线接上之后，"已经写了 6 页"曾经是模型真写完的闭合页数（`readPlanProgress` 只认闭合的
 *   字符串与对象）。**2026-10-21 晚这一行整个换掉了**——不再报页数：
 *
 *   - `PLAN_LINES`（轮播那四句）：一个数都不许有（它们要在第一段增量到达之前就说话）。
 *   - `writingLineOf()`：**只说"正在思考中"**，不再摆 k / N。
 *     换掉的理由是屏幕上那两句假话：分子是**表里的节点数**、分母是**请求的页数**，
 *     共读版两个单位不同（写出来是"已写 12 / 8 页"）；独读版虽然同单位，
 *     那个数说的是"模型写了几个 JSON 对象"，不是家长关心的"故事到哪儿了"。
 *     一句"正在思考中"不会说错，而下面那半截真写出来的故事本身就是最好的进度。
 *
 * 为什么它值得单独一个文件（而不是写在 `Desk.tsx` 里）：与 `studio/wait-copy.ts`
 *   同一个理由——能被 node 钉住的东西不该住在组件里。这里的纪律是"哪一个数能说、
 *   哪一个数不能说"，而那种东西写在 JSX 旁边的注释里，下一刀改文案的人顺手就会破坏它。
 *   （★ 那四句的读者只有 `Desk` 编故事那一段，`useRotatingLine` 负责播；
 *     `writingLineOf` 的读者也是它。）
 */

/**
 * 编故事那几分钟轮着说的四句。
 *
 * 顺序是有讲究的：从"想开头"到"分页"到"给每一页想画面"，是这一趟活的自然顺序，
 *   而最后一句是安抚（"还在写"），摆在最后是因为它最像"快好了"——
 *   实测（工单 01 的收口记录）规划这一趟 12 个主题里跑过 2 次重写，
 *   所以不能每一句都像马上要结束。
 *
 * 四句都不含任何时刻、页数、百分比；也不出现"还剩""马上"这类承诺。
 *   "一小会儿"是唯一一个时间感的词，它与工作台那四句里那一句是同一个说法
 *   （同一批文案，别在这里换一个"稍等片刻"）。
 */
export const PLAN_LINES = [
  '正在想这个故事怎么开头',
  '正在把故事分成一页一页',
  '正在给每一页想画面',
  '还在写，再等一小会儿',
] as const

/**
 * 真的在写的时候那一句：**「正在思考中」**（2026-10-21 晚改的，此前报"已写 k / N 页"）。
 *
 * 为什么不再报页数——两个理由，一个是那次屏幕上的假话，一个是更根本的：
 *
 * 1. 分子与分母**不是一个单位**。分子是 `readPlanProgress` 数出来的**表里节点数**，
 *    分母是**请求的页数**。独读版两者相等；共读版不等（分母是"一条路走下来几页"，
 *    表里一定有 `{pages}+({pages}−C)` 个节点），于是屏幕上写成了"已写 12 / 8 页"。
 * 2. 就算同单位，那个数说的也是"模型写了几个 JSON 对象"，不是家长关心的"故事到哪儿了"。
 *    而下面那半截**真写出来的故事**本身就是最好的进度——它一页一页长出来，不用翻译成数字。
 *
 * `pages === 0` 时仍然返回 `null`：一段都还没写出来时，上面轮播的那一句正在说话，
 *   这一行此刻还没有话可说（"正在思考中"与"正在想这个故事怎么开头"并排是重复的）。
 */
export function writingLineOf(args: { pages: number }): string | null {
  return args.pages > 0 ? '正在思考中' : null
}
