/**
 * run-phase-lines.ts —— 画桌上方那一句主句（纯函数，无 React）
 *
 * 2026-10-21 从 `GenerationRun.tsx` 里拔出来（工单 D-34）：那一屏的六档 phase
 *   各有一句话要说，而六句话连同它们背后的来历（用户原话、"为什么是这样措辞"）
 *   原来压在组件的中段，把 state 与动作挤在两页之外。
 *
 * 为什么是纯函数而不是一个 hook：与 `plan-lines.ts` / `studio/wait-copy.ts` 同一条先例
 *   —— 能被 node 钉住的东西不该住在组件里。这里能被钉住的是**优先级**：
 *   同一刻有两档同时成立时（`ready` 与 `published`），说出口的必须是哪一句。
 *   `run-phase-lines.test.ts` 钉的就是这个。
 *
 * ★ 这一句是这一屏上最大的一行字，所以它只说两件事：
 *   **现在在做什么**、**接下来会发生什么**。不说时刻、不说百分比（与 `plan-lines.ts`
 *   同一条纪律；那两句在"编故事"那一段尤其容易犯）。
 */

import type { Phase } from './phase.ts'

export type PhaseLineInput = {
  phase: Phase
  /** 闸门那一屏开着（`phase === 'story'` 且故事在手） */
  atGate: boolean
  /** 正在重写一版（`working === 'rewriting'`） */
  rewriting: boolean
  /** 已经装订（只有 `ready` 那一档读它） */
  published: boolean
  /**
   * 服务端这一刻还在跑（`GET /events` 的 status 帧说的）。
   * 只有"重放"那一档读它：那一档分不出"还在跑"与"这一轮死掉了"，
   * 而这两种情况的下一步完全不同。
   */
  serverRunning: boolean
}

/**
 * `null` = 这一档没有主句要说（调用方不渲染那一行）。
 */
export function phaseLineOf(input: PhaseLineInput): string | null {
  const { phase, atGate, rewriting, published, serverRunning } = input

  /**
   * 「编好之后会停下来让你先看一眼……」——**接下来会发生什么**。
   *
   * ★ 2026-10-18：这一句原来是从「正在编故事。编好之后会停下来……」起头的，
   *   而画桌上方那一行（`.dk__stage`）说的是同一件事——同一句话说两遍，
   *   读的人会开始怀疑哪一处才对（`Desk.tsx` 文件头第 ① 条就是为这条删掉了
   *   原来那一行 `dk__head`）。所以"正在编故事"这份活**只在画桌那一行说**，
   *   这里留下的是那个承诺。
   */
  if (phase === 'planning') return '编好之后会停下来让你先看一眼，你说画才开始画。'

  if (atGate) {
    /**
     * ★ 闸门那一屏的主句（2026-10-17）：说清**为什么停在这儿**——钱还没花。
     *
     * ★ 2026-10-18：重写那一段时间它换一句（用户："前端什么反馈都没有……
     *   这样用户怎么知道有没有重新生成故事呢"）。这一句是**这一屏上最大的一行字**，
     *   而原来它在那 101 秒里一个字都不变；换掉的这一句同时答两个问题：
     *   现在在做什么、做完之后会怎样。
     */
    return rewriting
      ? '正在按你说的重写这一版故事——写好了这一屏会自己换过来，你刚写的那句还留在框里。'
      : '故事写好了，先看一遍——不满意的地方直接改，改完点「就按这个画」才出图。图是按你改好的这一版画的。'
  }

  if (phase === 'running') {
    /**
     * ★ 2026-10-16 用户划掉了原来那句「这期间先不用管它，**也别关这个页面**」，
     *   要求写成："如果不想等待，可以等生成好之后在书架里找到并编辑。"
     *   ★ 那句话不只是口气不好，它**在拦一件不必拦的事**：这一轮跑在服务端
     *     （`/api/books` 文件头第 2 条：浏览器关了照旧落盘），关掉页面既不会中断它，
     *     也不会丢掉已经画好的那些页。所以现在说的是**这一本怎么找回来**。
     *   ★ 「这一轮不会停」五个字留着不删：不说的话，"可以先离开"读起来像"放弃它"。
     */
    return '正在一页一页做。不想等的话可以先离开，这一轮不会停——做完之后在书架的「正在编辑」里找它，在那里接着编辑。'
  }

  if (phase === 'replaying') {
    if (!serverRunning) return '这一轮没有跑完（连接断了）。下面是你已经做出来的部分。'
    /**
     * 2026-10-17 改了后半句：原来写的是"刷新这一页就能看到"——用户实测报的
     *   正是"我看不到画的什么"。现在这一屏自己会重读日志（`use-run-poll.ts`），
     *   所以照实说它会自己长出来，别让人去手动刷。
     */
    return '这一轮在服务器上跑着，下面这几格会自己长出来——不想等可以先去做别的。'
  }

  if (phase === 'ready') {
    return published
      ? '这本已经装订好了。'
      : '每一页都做完了。不满意哪一页就在那一页重做；都没问题再点「确定生成」。'
  }

  if (phase === 'failed') return '下面这句话说了为什么。'

  // `'story'` 但闸门没开（故事不在手上）：一句都不说，不编一句话出来
  return null
}
