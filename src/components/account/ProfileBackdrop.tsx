/**
 * ProfileBackdrop —— `/account` 那一屏的整屏背景：三团蓝光晕压在一层竖向底色上
 *
 * ★ 它是 `StudioBackdrop` 的**替身**，不是它的变体，所以是另一个组件：
 *   那一层是"与首页第一幕同一片天"（`scene-1.webp` + 纸光），
 *   这一层是**参考稿 `body` 的那四条渐变**（用户 2026-10-17：「复刻一下背景」）。
 *   两件事，两个读者，没有一处共用。
 *
 * ★ 谁挂它：`AppShell`。挂的位置与 `StudioBackdrop` 一模一样（`.shell` 的第一个孩子），
 *   因为这两个是**同一格上的两副面孔**——按路由二选一。放在 `account/` 而不是
 *   `shell/` 的理由是它消费的是这一屏自己的令牌组（`--pf-*`），
 *   与 `profile-home.css` 住在一起，改这一屏的配色时两处能一起看见。
 *
 * ★ 为什么是 `fixed` —— 这与 `StudioBackdrop` 的选择**相反**，所以要说清楚：
 *   · 那一层必须是 `absolute`，因为它是一张照片，而照片的对比度按文档分段量过
 *     （见 `studio-backdrop.css` 文件头那张十段表）：固定住之后，
 *     "这一行字压在天上清不清楚"就没有确定答案了。
 *   · 这一层是**两条渐变**（不是图），四条全是极浅的冷色，整屏亮度只在一个很窄的
 *     区间里走；所以"哪一行字压在哪儿"仍然是确定答案——量出**最深的那一点**就够了
 *     （`node scripts/check-scrim.mts` 的「个人主页那层蓝底」那一节，保守取法）。
 *     而它必须 `fixed`：三团光晕是**按视口定位**的（左上一团最浓），
 *     改成 `absolute` 铺满两千多像素的文档之后，那三团会被拉散、方向感就没了。
 *
 * ★ 它不是毛玻璃、也没有任何动效：一层静态渐变，画一次就不再变。
 *   真要加 `backdrop-filter` 会踩 docs/known-tradeoffs.md 那条账（固定元素做模糊 = 每帧重采样整屏）。
 *
 * ★ 它**不负责**兜 sidebar：`.shell__side` 自己那层纸（α=0.78）压在这层之上，
 *   两者合成之后的对比度也在同一支脚本里量着（那一节叫「侧栏那层纸」）。
 */
