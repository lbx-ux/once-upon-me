/**
 * StudioBackdrop —— 工作台背景：与首页第一幕**同一片天**
 *
 * 工作台原来是一块 `#faf5ee` 平涂，首页是三张水彩场景靠长交叉溶解连起来的满屏世界——
 * 两屏放在一起读起来像两个网站。这一层把 `scene-1.webp`（清晨天光，也就是用户从首页
 * 「开始创作」走进来之时所看到的那一片）接过来，四屏共用。
 *
 * ★ 它不是 `SceneBackdrop` 的简化版，是**另一件事**，所以另起一个组件而不是加属性：
 *   那套三幕 + 权重归一化 + 每次重量幕间距，是为「滚动叙事」建的（README §五）。
 *   工作台不叙事——它是一屏坐着做事的地方，`useScrollTick` 在这里没有消费者，
 *   硬接等于白背一条滚动循环。
 *
 * 两层，从下往上，都只占**文档顶部那一段**：
 *   1. `.sb__sky`  —— 那张天，`cover`，与首页第一幕同一档 `background-position`；
 *      再与 `--sky` multiply：这张图只有顶上 20% 是蓝的，剩下七成是准白，
 *      不做这层合成的话屏幕顶部只会是一条淡蓝带（理由与逐行读数见 css 文件头）
 *   2. `.sb__veil` —— 同一块高度上的竖向纸层：上薄下厚，到底变成纯纸
 *
 * ★ 它是 `absolute` 而不是 `fixed`。第一版按字面做了满屏 fixed + 一团径向阅读光，
 *   真机截图把它否掉了：那两团粉橘云铺满一整屏之后读起来是两块色斑，不是一片天；
 *   更要紧的是固定背景配会滚动的正文，"这一行字压在天光上清不清楚"就没有确定答案了。
 *   两条理由与推导写在 `studio-backdrop.css` 文件头。
 *
 * ★ 一条决定其余一切的设计规则（量的过程与读数见 `studio-backdrop.css` 文件头）：
 *   **压在天空带上的文字只允许 `--ink` 与 `--ink-on-sky`**；
 *   `--ink-muted` 与 `--accent` 做文字时必须在一张纸里
 *   （卡片的 `--surface`、侧栏那层纸、或天空带以下那段纯纸）。
 *   这不是新发明：README §五 第三屏那条「那两行本来就不该压在画上」是同一个结论的另一面。
 *
 * ★ 刻意**不做**的两件事，两条都是付过学费的（README §五）：
 *   - 不给任何一层加 `backdrop-filter`。固定元素做背景模糊 = 每帧滚动重采样它背后那块屏幕。
 *     首页为同一件事拆过 `.to-top` 与 `.btn--ghost`。
 *   - 不做视差位移。大图上任何 transform 都是每帧重采样一整屏。所以这里没有一处动。
 */

export default function StudioBackdrop() {
  return (
    <div className="sb" aria-hidden="true">
      <div className="sb__sky" />
      <div className="sb__veil" />
    </div>
  )
}
